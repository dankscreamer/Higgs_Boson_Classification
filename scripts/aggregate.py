"""Combine per-seed benchmark runs into report tables: mean ± sd over seeds, significance, scaling.

Reads results/subset<N>_seed<S>/{metrics,significance}.csv (runs from the current pipeline only) and
writes results/summary/: main_<N>.csv/.md, comparisons_<N>.csv/.md, scaling.csv, scaling.png, README.md.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from higgs.plots import plot_scaling  # noqa: E402

METRICS = ["roc_auc", "pr_auc", "accuracy", "log_loss", "brier", "ece", "ece_platt", "ece_isotonic",
           "train_seconds"]
# (a, b, question it answers): positive diff means a > b.
COMPARISONS = [
    ("xgboost|low", "logreg|low", "Trees vs linear on raw measurements"),
    ("xgboost|all", "logreg|all", "Trees vs linear on raw + expert"),
    ("xgboost|geo", "xgboost|low", "Feature engineering (geo) for trees"),
    ("logreg|geo", "logreg|low", "Feature engineering (geo) for the linear model"),
    ("xgboost|geo", "xgboost|high", "Geometry alone vs expert masses (XGB)"),
    ("xgboost|all", "xgboost|high", "Adding raw features to the masses (XGB)"),
    ("xgboost|geo_high", "xgboost|all", "geo+expert vs raw+expert (XGB)"),
    ("logreg|geo_high", "logreg|all", "geo+expert vs raw+expert (LogReg)"),
]


def load_runs() -> tuple[pd.DataFrame, pd.DataFrame]:
    metrics, sig = [], []
    for d in sorted((ROOT / "results").glob("subset*_seed*")):
        mpath, spath = d / "metrics.csv", d / "significance.csv"
        if not (mpath.exists() and spath.exists()):
            continue
        m = pd.read_csv(mpath)
        if "ece_platt" not in m:          # run from an older pipeline version
            continue
        n, seed = map(int, re.match(r"subset(\d+)_seed(\d+)", d.name).groups())
        metrics.append(m)
        s = pd.read_csv(spath)
        s["subset_size"], s["seed"] = n, seed
        sig.append(s)
    if not metrics:
        raise SystemExit("no benchmark runs found; run scripts/run_benchmark.py first")
    return pd.concat(metrics, ignore_index=True), pd.concat(sig, ignore_index=True)


def fmt(mean: float, sd: float, digits: int = 4) -> str:
    return f"{mean:.{digits}f}" if pd.isna(sd) else f"{mean:.{digits}f} ± {sd:.{digits}f}"


def main() -> None:
    metrics, sig = load_runs()
    out = ROOT / "results" / "summary"
    out.mkdir(parents=True, exist_ok=True)
    readme = ["# Benchmark summary (generated by scripts/aggregate.py)", ""]

    for n, g in metrics.groupby("subset_size"):
        agg = g.groupby(["model", "feature_set"])[METRICS].agg(["mean", "std"])
        agg.columns = [f"{a}_{b}" for a, b in agg.columns]
        agg["n_seeds"] = g.groupby(["model", "feature_set"]).seed.nunique()
        agg = agg.reset_index().sort_values("roc_auc_mean", ascending=False)
        agg.to_csv(out / f"main_{n}.csv", index=False)
        seeds = sorted(int(s) for s in g.seed.unique())
        lines = [f"## Budget {n:,} events ({len(seeds)} seeds: {seeds}), test = 500k fixed events", "",
                 "| model | features | ROC AUC | PR AUC | ECE raw | ECE Platt | Brier | train s |", "|---|---|---|---|---|---|---|---|"]
        for r in agg.itertuples():
            lines.append(f"| {r.model} | {r.feature_set} | {fmt(r.roc_auc_mean, r.roc_auc_std)} | "
                         f"{fmt(r.pr_auc_mean, r.pr_auc_std)} | {fmt(r.ece_mean, r.ece_std)} | "
                         f"{fmt(r.ece_platt_mean, r.ece_platt_std)} | {fmt(r.brier_mean, r.brier_std)} | "
                         f"{fmt(r.train_seconds_mean, r.train_seconds_std, 1)} |")
        (out / f"main_{n}.md").write_text("\n".join(lines) + "\n")
        readme += lines + [""]

        s = sig[sig.subset_size == n]
        rows = []
        for a, b, question in COMPARISONS:
            fwd = s[(s.a == a) & (s.b == b)][["seed", "diff", "p_value"]]
            rev = s[(s.a == b) & (s.b == a)][["seed", "diff", "p_value"]].assign(diff=lambda d: -d["diff"])
            both = pd.concat([fwd, rev])
            if both.empty:
                continue
            rows.append({"a": a, "b": b, "question": question, "n_seeds": len(both),
                         "diff_mean": both["diff"].mean(), "diff_sd": both["diff"].std(),
                         "seeds_a_better_p05": int(((both["diff"] > 0) & (both.p_value < 0.05)).sum()),
                         "seeds_b_better_p05": int(((both["diff"] < 0) & (both.p_value < 0.05)).sum()),
                         "max_p_value": both.p_value.max()})
        comp = pd.DataFrame(rows)
        comp.to_csv(out / f"comparisons_{n}.csv", index=False)
        lines = [f"### Paired DeLong tests at {n:,} (per seed, α = 0.05)", "",
                 "| question | A | B | ΔAUC (A−B) mean ± sd | seeds A sig. better | seeds B sig. better |", "|---|---|---|---|---|---|"]
        lines += [f"| {r.question} | {r.a} | {r.b} | {fmt(r.diff_mean, r.diff_sd)} | {r.seeds_a_better_p05}/{r.n_seeds} | "
                  f"{r.seeds_b_better_p05}/{r.n_seeds} |" for r in comp.itertuples()]
        (out / f"comparisons_{n}.md").write_text("\n".join(lines) + "\n")
        readme += lines + [""]

    scaling = (metrics[metrics.model.isin(["logreg", "xgboost"])]
               .groupby(["model", "feature_set", "subset_size"])
               .agg(n_train=("n_train", "first"), auc_mean=("roc_auc", "mean"), auc_sd=("roc_auc", "std"),
                    seconds_mean=("train_seconds", "mean"), n_seeds=("seed", "nunique")).reset_index())
    scaling.to_csv(out / "scaling.csv", index=False)
    if scaling.subset_size.nunique() > 1:
        plot_scaling(scaling, out / "scaling.png")
        readme += ["## Data-budget scaling", "", "![scaling](scaling.png)", ""]
    (out / "README.md").write_text("\n".join(readme))
    print("\n".join(readme))


if __name__ == "__main__":
    main()
